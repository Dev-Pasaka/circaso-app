#!/usr/bin/env python3
"""Regenerate the logo vector drawables from the geometry of assets/brand/circaso-mark.svg.

Android vector drawables have no masks, but the SVG builds the mark with one (disc minus a ring minus a wedge).
This script writes that shape out as real outlines (the wedge/circle intersections are computed here) and offsets the
thin strokes so only their visible half is drawn. Output:
  shared/src/commonMain/composeResources/drawable/circaso_mark{,_black,_white}.xml   (Compose resources, both platforms)
  (the splash icon is NOT generated: it is a 1024 px bitmap, because the system rasterises vectors at low resolution there)
  androidApp/src/main/res/drawable{,-v24}/ic_launcher_*.xml, mipmap-anydpi-v26/*.xml  (adaptive icon + monochrome layer)
Run from the project root: python3 .claude/skills/circaso-mobile/scripts/make_logo_vectors.py
"""
import math, os

cx = cy = 100.0
U0, L0 = (143.6, 80.0), (143.6, 120.0)
du, dl = (96.4, -40.0), (96.4, 40.0)


def hit(p0, d, r):
    a = d[0] ** 2 + d[1] ** 2
    b = 2 * ((p0[0] - cx) * d[0] + (p0[1] - cy) * d[1])
    c = (p0[0] - cx) ** 2 + (p0[1] - cy) ** 2 - r * r
    t = (-b + math.sqrt(b * b - 4 * a * c)) / (2 * a)
    return (p0[0] + t * d[0], p0[1] + t * d[1])


def f(p):
    return f"{p[0]:.2f},{p[1]:.2f}"


def at_radius(p, r):
    ang = math.atan2(p[1] - cy, p[0] - cx)
    return (cx + r * math.cos(ang), cy + r * math.sin(ang))


def unit(d):
    m = math.hypot(*d)
    return (d[0] / m, d[1] / m)


Au, Al = hit(U0, du, 92), hit(L0, dl, 92)
Vu, Vl = hit(U0, du, 83), hit(L0, dl, 83)
Wu, Wl = hit(U0, du, 91), hit(L0, dl, 91)
U1, L1 = at_radius(U0, 48.6), at_radius(L0, 48.6)
nu = (-abs(unit(du)[1]), -abs(unit(du)[0]))  # away from the wedge: up and left
nl = (-abs(unit(dl)[1]), abs(unit(dl)[0]))   # down and left
shift = lambda p, n: (p[0] + n[0] * 0.6, p[1] + n[1] * 0.6)

cshape = f"M{f(Au)} A92,92 0 1 0 {f(Al)} L{f(L0)} A48,48 0 1 1 {f(U0)} Z"
dot = "M80,100 A20,20 0 1 0 120,100 A20,20 0 1 0 80,100 Z"

HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Circaso mark, generated by make_logo_vectors.py from circaso-mark.svg. Do not edit by hand. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="200dp" android:height="200dp" android:viewportWidth="200" android:viewportHeight="200">\n')
METAL = '''        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="35.6" android:startY="17.2" android:endX="164.4" android:endY="182.8">
                <item android:offset="0" android:color="#FFFBFBFD" />
                <item android:offset="0.32" android:color="#FFD4D5D9" />
                <item android:offset="0.55" android:color="#FF8F9298" />
                <item android:offset="0.78" android:color="#FFDCDDE1" />
                <item android:offset="1" android:color="#FFF4F4F6" />
            </gradient>
        </aapt:attr>
'''
HIGHLIGHT = '''        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="66.9" android:centerY="55.8" android:gradientRadius="101.2">
                <item android:offset="0" android:color="#BFFFFFFF" />
                <item android:offset="1" android:color="#00FFFFFF" />
            </gradient>
        </aapt:attr>
'''


def shapes(block):
    return f'    <path android:pathData="{cshape}">\n{block}    </path>\n    <path android:pathData="{dot}">\n{block}    </path>\n'


def metallic():
    s = HEAD + shapes(METAL) + shapes(HIGHLIGHT)
    s += f'    <path android:pathData="M{f(Vu)} A83,83 0 1 0 {f(Vl)}" android:strokeColor="#73FFFFFF" android:strokeWidth="1.4" />\n'
    s += f'    <path android:pathData="M{f(Wu)} A91,91 0 1 0 {f(Wl)}" android:strokeColor="#595D6066" android:strokeWidth="1.2" />\n'
    s += f'    <path android:pathData="M{f(L1)} A48.6,48.6 0 1 1 {f(U1)}" android:strokeColor="#593B3D42" android:strokeWidth="1.2" />\n'
    s += '    <path android:pathData="M100,80.6 A19.4,19.4 0 1 0 100,119.4 A19.4,19.4 0 1 0 100,80.6" android:strokeColor="#593B3D42" android:strokeWidth="1.2" />\n'
    s += f'    <path android:pathData="M{f(shift(U0, nu))} L{f(shift(Au, nu))} M{f(shift(L0, nl))} L{f(shift(Al, nl))}" android:strokeColor="#593B3D42" android:strokeWidth="1.2" />\n'
    return s + '</vector>\n'


def mono(color):
    return HEAD + f'    <path android:pathData="{cshape}" android:fillColor="{color}" />\n    <path android:pathData="{dot}" android:fillColor="{color}" />\n</vector>\n'


def adaptive(color):
    s = 0.66 * 108 / 200  # same proportions as circaso-icon.svg
    t = 54 - 100 * s
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Circaso mark in the adaptive-icon safe zone (generated). -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            f'    <group android:translateX="{t:.3f}" android:translateY="{t:.3f}" android:scaleX="{s:.5f}" android:scaleY="{s:.5f}">\n'
            f'        <path android:pathData="{cshape}" android:fillColor="{color}" />\n'
            f'        <path android:pathData="{dot}" android:fillColor="{color}" />\n    </group>\n</vector>\n')


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(text)


cmp = "shared/src/commonMain/composeResources/drawable/"
res = "androidApp/src/main/res/"
write(cmp + "circaso_mark.xml", metallic())
write(cmp + "circaso_mark_black.xml", mono("#FF0B0B0C"))
write(cmp + "circaso_mark_white.xml", mono("#FFFFFFFF"))
write(res + "drawable-v24/ic_launcher_foreground.xml", adaptive("#FFFFFFFF"))
write(res + "drawable/ic_launcher_monochrome.xml", adaptive("#FF000000"))
write(res + "drawable/ic_launcher_background.xml",
      '<?xml version="1.0" encoding="utf-8"?>\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
      '    <path android:pathData="M0,0h108v108h-108z" android:fillColor="#FF0B0B0C" />\n</vector>\n')
for name in ("ic_launcher", "ic_launcher_round"):
    write(res + f"mipmap-anydpi-v26/{name}.xml",
          '<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          '    <background android:drawable="@drawable/ic_launcher_background" />\n    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
          '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n</adaptive-icon>\n')
print("written")
