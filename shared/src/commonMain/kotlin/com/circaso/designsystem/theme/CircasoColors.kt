package com.circaso.designsystem.theme

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import kotlin.math.roundToInt

/** Semantic colour roles from the design tokens. Screens use roles, never raw hex. */
@Immutable
data class CircasoColors(
    val bg: Color,
    val bgGrouped: Color,
    val surface: Color,
    val surfaceRaised: Color,
    val fill: Color,
    val fillStrong: Color,
    val fillSelected: Color,
    val separator: Color,
    val ink: Color,
    val inkSecondary: Color,
    val inkTertiary: Color,
    val action: Color,
    val onAction: Color,
    val money: Color,
    val moneySurface: Color,
    val moneyCard: Color,
    val moneyCardSheen: Color,
    val onMoney: Color,
    val critical: Color,
    val warning: Color,
    val focus: Color,
    val glass: Color,
    val glassEdge: Color,
    val scrim: Color,
    val isDark: Boolean,
    /** The high-contrast themes: controls that are borderless elsewhere keep a visible edge (WCAG 1.4.11). */
    val isHighContrast: Boolean = false,
)

private fun rgba(r: Int, g: Int, b: Int, a: Float) = Color(r, g, b, (a * 255).roundToInt())

